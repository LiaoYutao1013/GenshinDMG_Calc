            'EHoldMix', 0.10, ...
            'Q', 0.95, ...
            'Daruma', 12.00), ...
        'Actions', actions);

    [totalDMG, dps, breakdown, rotationTime, audit] = simulateSimpleCharacterDPS( ...
        'Sayu', build, enemy, seqFile, talentLevel, constellation, teamContext, spec);
end

function element = localResolveSayuAbsorbedElement(teamContext, enemy)
    if nargin >= 2 && isstruct(enemy)
        initialAura = string(getFieldOrDefault(enemy, 'InitialAuraElement', ""));
        if any(strcmpi(initialAura, ["Pyro", "Hydro", "Electro", "Cryo"]))
            element = string(initialAura);
            return;
        end
    end

    priority = ["Pyro", "Hydro", "Electro", "Cryo"];
    for i = 1:numel(priority)
        if getFieldOrDefault(teamContext, char(priority(i) + "Count"), 0) >= 1
            element = priority(i);
            return;
        end
    end
    element = "";
end

function tf = localSayuAllowsAmplify(element, teamContext)
    switch lower(char(string(element)))
        case 'pyro'
            tf = double(getFieldOrDefault(teamContext, 'HydroCount', 0) >= 1 || getFieldOrDefault(teamContext, 'CryoCount', 0) >= 1);
        case 'hydro'
            tf = double(getFieldOrDefault(teamContext, 'PyroCount', 0) >= 1);
        case 'cryo'
            tf = double(getFieldOrDefault(teamContext, 'PyroCount', 0) >= 1);
        otherwise
            tf = 0;
    end
end

function tf = localSayuAllowsCatalyze(element, teamContext)
    switch lower(char(string(element)))
        case 'electro'
            tf = double(getFieldOrDefault(teamContext, 'DendroCount', 0) >= 1);
        otherwise
            tf = 0;
    end
end

function aura = localSayuPreferredAura(element, teamContext)
    switch lower(char(string(element)))
        case 'pyro'
            if getFieldOrDefault(teamContext, 'HydroCount', 0) >= 1
                aura = "Hydro";
            elseif getFieldOrDefault(teamContext, 'CryoCount', 0) >= 1
                aura = "Cryo";
            else
                aura = "";
            end
        case 'hydro'
            aura = "Pyro";
        case 'cryo'
            aura = "Pyro";
        otherwise
            aura = "";
    end
end
