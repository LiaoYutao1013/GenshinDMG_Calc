    if nargin < 4 || isempty(talentLevel)
        talentLevel = 10;
    end
    if nargin < 5 || isempty(constellation)
        constellation = 0;
    end
    if nargin < 6 || isempty(teamContext)
        teamContext = buildTeamContext({struct('Name', 'Sayu', 'Constellation', constellation, 'Build', build)}, 20, struct());
    end

    absorbedElement = localResolveSayuAbsorbedElement(teamContext, enemy);
    absorbedReady = double(strlength(absorbedElement) > 0);
    emValue = getFieldOrDefault(build, 'EM', 0) + getFieldOrDefault(teamContext, 'EMBonus', 0);
    c6DarumaAtkBonus = min(4.0, 0.002 * emValue) * double(constellation >= 6);

    actions = struct();
    actions.EPress = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "xFuufuuWhirlwindKickPressDMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Anemo", ...
        'BaseMultiplier', 1.00, ...
        'AllowTransformative', 1, ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ElementalArt_Click", ...
        'LunarisDamageParam', "Click_StrikeDamage", ...
        'Note', "Fuuin Dash press");
    actions.Roll = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "FuufuuWindwheelDMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Anemo", ...
        'BaseMultiplier', 1.00, ...
        'HitCount', 8, ...
        'HitTimeline', 0.55 * ones(1, 8), ...
        'AllowTransformative', 1, ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ElementalArt_Roll_Bullet", ...
        'LunarisDamageParam', "Roll_Damage", ...
        'Note', "Windwheel roll");
    actions.RollMix = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "FuufuuWindwheelElementalDMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', absorbedElement, ...
        'BaseMultiplier', absorbedReady, ...
        'HitCount', 8, ...
        'HitTimeline', 0.55 * ones(1, 8), ...
        'AllowAmplify', localSayuAllowsAmplify(absorbedElement, teamContext), ...
        'AllowCatalyze', localSayuAllowsCatalyze(absorbedElement, teamContext), ...
        'PreferredAmplifyAura', localSayuPreferredAura(absorbedElement, teamContext), ...
        'ApplyGauge', 1.0 * absorbedReady, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ElementalArt_Roll_Bullet", ...
        'LunarisDamageParam', "MixRoll_Damage", ...
        'Note', "Absorbed roll damage");
    actions.EHoldEnd = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "FuufuuWhirlwindKickHoldDMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Anemo", ...
        'BaseMultiplier', 1.00, ...
        'AllowTransformative', 1, ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ElementalArt_Hold", ...
        'LunarisDamageParam', "Hold_StrikeDamage", ...
        'Note', "Hold finisher");
    actions.EHoldMix = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "FuufuuWhirlwindKickElementalDMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', absorbedElement, ...
        'BaseMultiplier', absorbedReady, ...
        'AllowAmplify', localSayuAllowsAmplify(absorbedElement, teamContext), ...
        'AllowCatalyze', localSayuAllowsCatalyze(absorbedElement, teamContext), ...
        'PreferredAmplifyAura', localSayuPreferredAura(absorbedElement, teamContext), ...
        'ApplyGauge', 1.0 * absorbedReady, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ElementalArt_Hold", ...
        'LunarisDamageParam', "Hold_Mix_StrikeDamage", ...
        'Note', "Absorbed hold finisher");
    actions.Q = struct( ...
        'TalentGroup', "Burst", ...
        'Param', "SkillActivationDMG", ...
        'DamageField', "BurstDMGBonus", ...
        'ActionElement', "Anemo", ...
        'BaseMultiplier', 1.00, ...
        'AllowTransformative', 1, ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ElementalBurst", ...
        'LunarisDamageParam', "Damage_Ratio", ...
        'Note', "Mujina Flurry cast");
    actions.Daruma = struct( ...
        'TalentGroup', "Burst", ...
        'Param', "MujiMujiDarumaDMG", ...
        'DamageField', "BurstDMGBonus", ...
        'ActionElement', "Anemo", ...
        'BaseMultiplier', 1.00 + c6DarumaAtkBonus, ...
        'AllowTransformative', 1, ...
