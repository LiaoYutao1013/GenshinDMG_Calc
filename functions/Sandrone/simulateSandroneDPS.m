function note = localAppendReactionTags(baseNote, reactionTags)
    note = string(baseNote);
    if isempty(reactionTags)
        return;
    end
    for i = 1:numel(reactionTags)
        if strlength(reactionTags(i)) == 0
            continue;
        end
        if strlength(note) == 0
            note = string(reactionTags(i));
        else
            note = note + ", " + string(reactionTags(i));
        end
    end
end

