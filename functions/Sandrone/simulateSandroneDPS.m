function state = localAdvanceStateWindow(state, actionName, deltaTime, talent, constellation)
    deltaTime = max(0, double(deltaTime));
    if deltaTime <= 1e-9
        return;
    end

    state.C4Cooldown = max(0, state.C4Cooldown - deltaTime);
    state.PolestarFieldTime = max(0, state.PolestarFieldTime - deltaTime);

    if state.DecodingActive
        powerGain = getTalentValue(talent, 'Passive', 'BeamPowerGainPerSecond', 10) * deltaTime;
        if constellation >= 1
            powerGain = powerGain * (1 - getTalentValue(talent, 'Constellation', 'C1PowerGainReduction', 10));
        end
        state.FagioPower = min(100, state.FagioPower + powerGain);
        if state.FagioPower >= 100
            state.DecodingActive = false;
            state.OverdriveActive = true;
        end
    elseif ~strcmpi(char(string(actionName)), 'E')
        powerDecay = getTalentValue(talent, 'Passive', 'NonDecodingPowerDecayPerSecond', 10) * deltaTime;
        state.FagioPower = max(0, state.FagioPower - powerDecay);
    end

    if state.OverdriveActive && state.FagioPower < getTalentValue(talent, 'Passive', 'OverdriveExitThreshold', 10)
        state.OverdriveActive = false;
    end
    state = localRefreshStellarConductFromField(state);
end

function state = localRefreshStellarConductFromField(state)
    state.StellarConductActive = state.PolestarFieldTime > 1e-6;
end

