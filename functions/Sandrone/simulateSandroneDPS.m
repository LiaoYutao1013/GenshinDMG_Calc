function [canApplyAura, icdStates, snapshot] = localResolveHitICD(icdStates, hitSpec, deltaTime)
    snapshot = struct( ...
        'ICDGroup', string(getFieldOrDefault(hitSpec, 'ICDGroup', "")), ...
        'ICDRule', string(getFieldOrDefault(hitSpec, 'ICDRule', "Independent")), ...
        'StrikeType', string(getFieldOrDefault(hitSpec, 'StrikeType', "")));
    canApplyAura = logical(getFieldOrDefault(hitSpec, 'CanApplyAura', false)) ...
        && double(getFieldOrDefault(hitSpec, 'ApplyGauge', 0)) > 0;
    if ~canApplyAura
        return;
    end

    icdConfig = localParseICDRule(snapshot.ICDRule);
    if strcmpi(char(string(getFieldOrDefault(icdConfig, 'Kind', "Independent"))), 'Independent')
        return;
    end
    if strlength(snapshot.ICDGroup) == 0
        return;
    end

    fieldName = matlab.lang.makeValidName(char(snapshot.ICDGroup));
    if ~isfield(icdStates, fieldName)
        icdStates.(fieldName) = struct( ...
            'HitsSinceApply', max(0, double(icdConfig.Hits) - 1), ...
            'Elapsed', max(0, double(icdConfig.Window)), ...
            'HitsThreshold', max(1, double(icdConfig.Hits)), ...
            'Window', max(0, double(icdConfig.Window)));
    end

    state = icdStates.(fieldName);
    state.Elapsed = state.Elapsed + max(0, double(deltaTime));
    if state.Window > 0 && state.Elapsed >= state.Window
        state.HitsSinceApply = max(0, state.HitsThreshold - 1);
        state.Elapsed = 0;
    end

    if state.HitsSinceApply >= max(0, state.HitsThreshold - 1)
        canApplyAura = true;
        state.HitsSinceApply = 0;
        state.Elapsed = 0;
    else
        canApplyAura = false;
        state.HitsSinceApply = state.HitsSinceApply + 1;
    end

    icdStates.(fieldName) = state;
end

function config = localParseICDRule(ruleText)
    ruleText = string(ruleText);
    config = struct('Kind', "Independent", 'Hits', 1, 'Window', 0);
    if strlength(ruleText) == 0 || strcmpi(char(ruleText), 'Independent')
        return;
    end
    tokens = regexp(lower(char(ruleText)), '(\d+)\s*hits?\s*/\s*([\d\.]+)\s*s', 'tokens', 'once');
    if isempty(tokens)
        return;
    end
    config.Kind = "Windowed";
    config.Hits = max(1, str2double(tokens{1}));
    config.Window = max(0, str2double(tokens{2}));
end

function multiplier = localStellarDamageMultiplier(talent, constellation, teamContext)
    multiplier = 1 ...
        + getFieldOrDefault(teamContext, 'StellarConductBonus', 0) ...
        + getFieldOrDefault(teamContext, 'SandroneStellarConductBonus', 0) ...
        + getFieldOrDefault(teamContext, 'SandroneStellarConductC1Bonus', 0) ...
        + getFieldOrDefault(teamContext, 'StellarGlimmerBonus', 0);
    if constellation >= 6
        multiplier = multiplier * (1 + getTalentValue(talent, 'Constellation', 'C6StellarConductElevate', 10));
    end
end

function damage = localDirectDamage(element, atk, mv, build, teamContext, enemy, extraBonus, extraResShred)
    if nargin < 8
        extraResShred = 0;
    end
    critRate = getFieldOrDefault(build, 'CritRate', 0) + localElementCritRateBonus(element, teamContext);
    critDMG = getFieldOrDefault(build, 'CritDMG', 0) + localElementCritDMGBonus(element, teamContext);
    critMult = calcExpectedCritMultiplier(critRate, critDMG);
    dmgBonus = 1 + localElementBonus(element, build, teamContext) + getFieldOrDefault(teamContext, 'AllDMGBonus', 0) + extraBonus;
    resShred = getFieldOrDefault(build, 'ResShred', 0) + localElementResShred(element, teamContext) + extraResShred;
    damage = atk * mv * dmgBonus * critMult * calcDamageMultiplier(90, enemy, resShred);
end

function bonus = localResolveDamageFieldBonus(build, damageField)
    damageField = string(damageField);
    bonus = getFieldOrDefault(build, char(damageField), 0);
    switch lower(char(damageField))
        case 'chargeddmgbonus'
            bonus = bonus + getFieldOrDefault(build, 'ChargeDMGBonus', 0);
        case 'chargedmgbonus'
            bonus = bonus + getFieldOrDefault(build, 'ChargedDMGBonus', 0);
    end
end

function bonus = localElementBonus(element, build, teamContext)
    switch lower(char(string(element)))
        case 'cryo'
