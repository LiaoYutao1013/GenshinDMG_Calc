function [totalDMG, dps, breakdown, rotationTime, audit] = simulateKleeDPS(build, enemy, seqFile, talentLevel, constellation, teamContext)
    % Klee simulator with normal / charged bomb string, Jumpy Dumpty split,
    % burst salvos, and key constellation damage segments.
    if nargin < 3 || isempty(seqFile)
        seqFile = fullfile(fileparts(mfilename('fullpath')), '..', '..', 'data', 'Klee', 'rotation_Klee.txt');
    end
    if nargin < 4 || isempty(talentLevel)
        talentLevel = 10;
    end
    if nargin < 5 || isempty(constellation)
        constellation = 0;
    end
    if nargin < 6 || isempty(teamContext)
        teamContext = buildTeamContext({struct('Name', 'Klee', 'Constellation', constellation, 'Build', build)}, 20, struct());
    end

    talent = readtable(char(resolveCharacterDataFile('Klee', 'talents')));
    burstLevel = talentLevel + 3 * double(constellation >= 5);
    burstTickMV = getTalentValue(talent, 'Burst', 'SparksnSplashDMG', burstLevel);
    burstTicks = 12;
    vaporizeReady = getFieldOrDefault(teamContext, 'HydroCount', 0) >= 1;
    c1ExtraMV = 1.20 * burstTickMV * double(constellation >= 1);
    c2DefReduct = 0.23 * double(constellation >= 2);
    c4ExplosionMV = 5.55 * (1 + double(constellation >= 4));
    c6PyroBonus = 0.50 * double(constellation >= 6);

    workBuild = build;
    workBuild.PyroDMGBonus = getFieldOrDefault(workBuild, 'PyroDMGBonus', 0) + c6PyroBonus;

    actions = struct();
    actions.N1 = localMakeKleePyroNormal("x1HitDMG", "NoarmalAttack_01_Damage", "NormalAttack_01_Damage", "Normal 1", double(vaporizeReady));
    actions.N2 = localMakeKleePyroNormal("x2HitDMG", "NoarmalAttack_02_Damage", "NormalAttack_02_Damage", "Normal 2", double(vaporizeReady));
    actions.N3 = localMakeKleePyroNormal("x3HitDMG", "NoarmalAttack_03_Damage", "NormalAttack_03_Damage", "Normal 3", double(vaporizeReady));
    actions.CA = struct( ...
        'TalentGroup', "Normal", ...
        'Param', "ChargedAttackDMG", ...
        'DamageField', "ChargedDMGBonus", ...
        'ActionElement', "Pyro", ...
        'BaseMultiplier', 1.50, ...
        'AllowAmplify', double(vaporizeReady), ...
        'PreferredAmplifyAura', "Hydro", ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ExtraAttack_Clover_Bullet", ...
        'LunarisDamageParam', "ExtraAttack_Damage", ...
        'Note', "Charged attack with Explosive Spark");
    actions.E1 = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "JumpyDumptyDMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Pyro", ...
        'BaseMultiplier', 1.00, ...
        'AllowAmplify', double(vaporizeReady), ...
        'PreferredAmplifyAura', "Hydro", ...
        'EnemyDefReduct', c2DefReduct, ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "Jumping_Drug_Explode", ...
        'LunarisDamageParam', "ElementalArt_Damage_01", ...
        'Note', "Jumpy Dumpty bounce 1");
    actions.E2 = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "JumpyDumptyDMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Pyro", ...
        'BaseMultiplier', 1.00, ...
        'AllowAmplify', double(vaporizeReady), ...
        'PreferredAmplifyAura', "Hydro", ...
        'EnemyDefReduct', c2DefReduct, ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "Jumping_Drug_Explode2", ...
        'LunarisDamageParam', "ElementalArt_Damage_02", ...
        'Note', "Jumpy Dumpty bounce 2");
    actions.E3 = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "JumpyDumptyDMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Pyro", ...
        'BaseMultiplier', 1.00, ...
        'AllowAmplify', double(vaporizeReady), ...
        'PreferredAmplifyAura', "Hydro", ...
        'EnemyDefReduct', c2DefReduct, ...
        'ApplyGauge', 2.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "Jumping_Drug_Explode3", ...
        'LunarisDamageParam', "ElementalArt_Damage_03", ...
        'Note', "Jumpy Dumpty bounce 3");
    actions.Mines = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "MineDMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Pyro", ...
        'BaseMultiplier', 1.00, ...
        'HitCount', 6, ...
        'HitTimeline', [0.35, 0.35, 0.35, 0.35, 0.35, 0.35], ...
        'AllowAmplify', double(vaporizeReady), ...
        'PreferredAmplifyAura', "Hydro", ...
        'EnemyDefReduct', c2DefReduct, ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "Mine", ...
        'LunarisDamageParam', "ElementalArt_Mine_Damage", ...
        'Note', "Jumpy Dumpty mines");
    actions.Q = struct( ...
        'TalentGroup', "Burst", ...
        'Param', "SparksnSplashDMG", ...
        'DamageField', "BurstDMGBonus", ...
        'ActionElement', "Pyro", ...
        'BaseMultiplier', 1.00, ...
        'PostSetBurstActiveTime', 10.0, ...
        'AllowAmplify', double(vaporizeReady), ...
        'PreferredAmplifyAura', "Hydro", ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "Elemental_Burst_Explode", ...
        'LunarisDamageParam', "ElementalBurst_Damage", ...
        'Note', "Sparks 'n' Splash cast");
    actions.QTicks = struct( ...
        'TalentGroup', "Burst", ...
        'Param', "SparksnSplashDMG", ...
        'DamageField', "BurstDMGBonus", ...
        'ActionElement', "Pyro", ...
        'BaseMultiplier', 1.00, ...
        'HitCount', burstTicks, ...
        'HitTimeline', [0.8 * ones(1, burstTicks - 1), 1.2], ...
        'AllowAmplify', double(vaporizeReady), ...
        'PreferredAmplifyAura', "Hydro", ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "Elemental_Burst_Explode", ...
        'LunarisDamageParam', "ElementalBurst_Damage", ...
        'Note', "Sparks 'n' Splash salvos");
    actions.C1Spark = struct( ...
        'TalentGroup', "Burst", ...
        'Param', "SparksnSplashDMG", ...
        'DamageField', "BurstDMGBonus", ...
        'ActionElement', "Pyro", ...
        'BaseMultiplier', c1ExtraMV, ...
        'MVOverride', 0, ...
        'FlatDirectATKWeight', c1ExtraMV, ...
        'AllowAmplify', double(vaporizeReady), ...
        'PreferredAmplifyAura', "Hydro", ...
        'ApplyGauge', 1.0 * double(constellation >= 1), ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "Constellation_Explode", ...
        'LunarisDamageParam', "Constellation_Explode_Damage", ...
        'Note', "C1 chained spark");
    actions.C4Exit = struct( ...
        'TalentGroup', "Burst", ...
        'Param', "SparksnSplashDMG", ...
        'DamageField', "BurstDMGBonus", ...
        'ActionElement', "Pyro", ...
        'MVOverride', c4ExplosionMV * double(constellation >= 4), ...
        'AllowAmplify', double(vaporizeReady), ...
        'PreferredAmplifyAura', "Hydro", ...
        'ApplyGauge', 2.0 * double(constellation >= 4), ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "Constellation_4", ...
        'LunarisDamageParam', "Klee_Constellation_4_Damage", ...
        'Note', "C4 burst exit explosion");

    defaultRotation = {'E1', 'E2', 'E3', 'Mines', 'N1', 'N2', 'CA', 'Q', 'QTicks'};
    if constellation >= 1
        defaultRotation{end + 1} = 'C1Spark'; %#ok<AGROW>
    end
    if constellation >= 4
        defaultRotation{end + 1} = 'C4Exit'; %#ok<AGROW>
    end

    spec = struct( ...
        'Element', "Pyro", ...
        'ScalingMode', "ATK", ...
        'PreferredAmplifyAura', "Hydro", ...
        'DefaultActionTime', 0.65, ...
        'DefaultRotation', {defaultRotation}, ...
        'ActionTimeMap', struct( ...
            'N1', 0.36, ...
            'N2', 0.39, ...
            'N3', 0.48, ...
            'CA', 0.92, ...
            'E1', 0.25, ...
            'E2', 0.25, ...
            'E3', 0.35, ...
            'Mines', 2.10, ...
            'Q', 0.92, ...
            'QTicks', 10.00, ...
            'C1Spark', 0.10, ...
            'C4Exit', 0.10), ...
        'Actions', actions);

    [totalDMG, dps, breakdown, rotationTime, audit] = simulateSimpleCharacterDPS( ...
        'Klee', workBuild, enemy, seqFile, talentLevel, constellation, teamContext, spec);
end

function action = localMakeKleePyroNormal(paramName, lunarisName, lunarisParam, note, allowAmplify)
    action = struct( ...
        'TalentGroup', "Normal", ...
        'Param', string(paramName), ...
        'DamageField', "NormalDMGBonus", ...
        'ActionElement', "Pyro", ...
        'BaseMultiplier', 1.00, ...
        'AllowAmplify', allowAmplify, ...
        'PreferredAmplifyAura', "Hydro", ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'StrikeType', "Blunt", ...
        'LunarisAttackName', string(lunarisName), ...
        'LunarisDamageParam', string(lunarisParam), ...
        'Note', string(note));
end
