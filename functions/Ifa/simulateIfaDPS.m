            'LunarisDamageParam', "ElementalBurst_ExtraHit_Damage", ...
            'AllowAmplify', double(any(strcmpi(absorbedElement, {'Hydro', 'Pyro', 'Cryo'})) && (pyroCount + hydroCount + cryoCount) >= 1), ...
