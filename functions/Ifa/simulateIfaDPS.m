function [totalDMG, dps, breakdown, rotationTime, audit] = simulateIfaDPS(build, enemy, seqFile, talentLevel, constellation, teamContext)
    % Ifa simulator with Nightsoul hover window, tap/hold Supporting Fire,
    % burst field marks, and constellation-aware extra tonic shots.
    if nargin < 3 || isempty(seqFile)
        seqFile = fullfile(fileparts(mfilename('fullpath')), '..', '..', 'data', 'Ifa', 'rotation_Ifa.txt');
    end
    if nargin < 4 || isempty(talentLevel)
        talentLevel = 10;
    end
    if nargin < 5 || isempty(constellation)
        constellation = 0;
    end
    if nargin < 6 || isempty(teamContext)
        teamContext = buildTeamContext({struct('Name', 'Ifa', 'Constellation', constellation, 'Build', build)}, 20, struct());
    end

    pyroCount = getFieldOrDefault(teamContext, 'PyroCount', 0);
    hydroCount = getFieldOrDefault(teamContext, 'HydroCount', 0);
    cryoCount = getFieldOrDefault(teamContext, 'CryoCount', 0);
    electroCount = getFieldOrDefault(teamContext, 'ElectroCount', 0);
    enemyTargetCount = max(1, round(getFieldOrDefault(enemy, 'TargetCount', ...
        getFieldOrDefault(enemy, 'EnemyCount', 1))));
    swirlReady = pyroCount + hydroCount + cryoCount + electroCount >= 1;

    absorbedElement = localResolveIfaBurstElement(teamContext);
    burstReactionReady = strcmpi(absorbedElement, 'electro') || strcmpi(absorbedElement, 'pyro') ...
        || strcmpi(absorbedElement, 'hydro') || strcmpi(absorbedElement, 'cryo');

    holdShotCount = 4 + double(constellation >= 6);
    holdTimeline = [0.00, 0.40, 0.40, 0.40, 0.40];
    holdTimeline = holdTimeline(1:holdShotCount);
    if numel(holdTimeline) < holdShotCount
        holdTimeline(end + 1:holdShotCount) = 0.40; %#ok<AGROW>
    end
    markHitCount = min(4, enemyTargetCount) * double(burstReactionReady);
    markTimeline = [1.60, zeros(1, max(0, markHitCount - 1))];

    actions = struct();
    actions.N1 = struct( ...
        'TalentGroup', "Normal", ...
        'Param', "x1HitDMG", ...
        'DamageField', "NormalDMGBonus", ...
        'ActionElement', "Anemo", ...
        'BaseMultiplier', 1.00, ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "NormalAttack_Bullet_01", ...
        'LunarisDamageParam', "NormalAttack_01_Damage", ...
        'AllowTransformative', double(swirlReady), ...
        'ReactionElement', "Anemo", ...
        'ReactionBaseDamage', 723.0, ...
        'Note', "Normal 1");
    actions.N2 = struct( ...
        'TalentGroup', "Normal", ...
        'Param', "x2HitDMG", ...
        'DamageField', "NormalDMGBonus", ...
        'ActionElement', "Anemo", ...
        'BaseMultiplier', 1.00, ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "NormalAttack_Bullet_02", ...
        'LunarisDamageParam', "NormalAttack_02_Damage", ...
        'AllowTransformative', double(swirlReady), ...
        'ReactionElement', "Anemo", ...
        'ReactionBaseDamage', 723.0, ...
        'Note', "Normal 2");
    actions.N3 = struct( ...
        'TalentGroup', "Normal", ...
        'Param', "x3HitDMG", ...
        'DamageField', "NormalDMGBonus", ...
        'ActionElement', "Anemo", ...
        'BaseMultiplier', 1.00, ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "NormalAttack_Bullet_03", ...
        'LunarisDamageParam', "NormalAttack_03_Damage", ...
        'AllowTransformative', double(swirlReady), ...
        'ReactionElement', "Anemo", ...
        'ReactionBaseDamage', 723.0, ...
        'Note', "Normal 3");
    actions.CA = struct( ...
        'TalentGroup', "Normal", ...
        'Param', "ChargedAttackDMG", ...
        'DamageField', "ChargedDMGBonus", ...
        'ActionElement', "Anemo", ...
        'BaseMultiplier', 1.00, ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ExtraAttack_Bullet", ...
        'LunarisDamageParam', "ExtraAttack_Damage", ...
        'AllowTransformative', double(swirlReady), ...
        'ReactionElement', "Anemo", ...
        'ReactionBaseDamage', 723.0, ...
        'Note', "Charged shot");
    actions.ECast = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "TonicshotDMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Anemo", ...
        'BaseMultiplier', 0.00, ...
        'PreSetCustomValue', 80, ...
        'PostSetSkillActiveTime', 7.5, ...
        'ApplyGauge', 0.0, ...
        'CanApplyAura', false, ...
        'CanTriggerReaction', false, ...
        'Note', "Airborne Disease Prevention");
    actions.SupportTap = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "TonicshotDMG", ...
        'DamageField', "NormalDMGBonus", ...
        'ActionElement', "Anemo", ...
        'BaseMultiplier', 1.00, ...
        'SkillWindowDamageBonus', 0.00, ...
        'ApplyGauge', 1.0, ...
        'ICDGroup', "Ifa_SupportingFire", ...
        'ICDRule', "2 hits / 12s", ...
        'LunarisAttackName', "HoverAttack_Bullet_01", ...
