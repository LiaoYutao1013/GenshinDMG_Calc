function value = localTableString(tbl, fieldName, rowIndex)
    value = "";
    if nargin < 3
        rowIndex = 1;
    end
    if isempty(tbl) || ~ismember(fieldName, tbl.Properties.VariableNames) || rowIndex > height(tbl)
        return;
    end
    value = string(tbl.(fieldName)(rowIndex));
end
