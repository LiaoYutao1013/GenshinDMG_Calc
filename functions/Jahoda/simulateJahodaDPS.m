function [totalDMG, dps, breakdown, rotationTime, audit] = simulateJahodaDPS(build, enemy, seqFile, talentLevel, constellation, teamContext)
    % Jahoda simulator with smoke-bomb fallback, flask discharge,
    % Moonsign meowball cadence, and timeline-aware robot conversion.
    if nargin < 3 || isempty(seqFile)
        seqFile = fullfile(fileparts(mfilename('fullpath')), '..', '..', 'data', 'Jahoda', 'rotation_Jahoda.txt');
    end
    if nargin < 4 || isempty(talentLevel)
        talentLevel = 10;
    end
    if nargin < 5 || isempty(constellation)
        constellation = 0;
    end
    if nargin < 6 || isempty(teamContext)
        teamContext = buildTeamContext({struct('Name', 'Jahoda', 'Constellation', constellation, 'Build', build)}, 20, struct(), enemy);
    end

    normalLevel = localClampTalentLevel(talentLevel);
    skillLevel = localClampTalentLevel(talentLevel + 3 * double(constellation >= 5));
    burstLevel = localClampTalentLevel(talentLevel + 3 * double(constellation >= 3));
    pyroCount = getFieldOrDefault(teamContext, 'PyroCount', 0);
    hydroCount = getFieldOrDefault(teamContext, 'HydroCount', 0);
    electroCount = getFieldOrDefault(teamContext, 'ElectroCount', 0);
    cryoCount = getFieldOrDefault(teamContext, 'CryoCount', 0);
    enemyTargetCount = max(1, round(getFieldOrDefault(enemy, 'TargetCount', getFieldOrDefault(enemy, 'EnemyCount', 1))));

    dominantElement = localResolveJahodaElement(teamContext);
    convertedElement = dominantElement;
    conversionReady = strlength(convertedElement) > 0;
    if ~conversionReady
        convertedElement = "Hydro";
    end
    moonsignActive = hasAscendantMoonsign(teamContext);
    enhancementElements = localResolveJahodaEnhancementElements(teamContext, constellation, moonsignActive);
    robotCount = 2 + double(any(strcmpi(enhancementElements, 'Electro')));
    robotInterval = 2.20 * (1 - 0.10 * double(any(strcmpi(enhancementElements, 'Cryo'))));
    robotHitCount = max(1, floor(12.0 / robotInterval));
    robotTimeline = robotInterval * ones(1, robotHitCount);
    robotDamageBonus = 0.30 * double(any(strcmpi(enhancementElements, 'Pyro')));
    meowballCount = 3;
    if moonsignActive
        meowballCount = 4;
    end
    meowballTimeline = 1.00 * ones(1, meowballCount);
    bounceCount = max(1, double(constellation >= 1) * meowballCount);
    bounceTimeline = 0.10 * ones(1, bounceCount);
