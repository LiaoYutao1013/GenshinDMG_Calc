    allowConvertedCatalyze = conversionReady && strcmpi(convertedElement, 'Electro');
    allowConvertedTransformative = conversionReady && any(strcmpi(convertedElement, {'Hydro', 'Pyro', 'Cryo', 'Electro'}));

