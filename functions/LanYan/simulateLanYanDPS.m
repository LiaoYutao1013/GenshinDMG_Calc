function element = localResolveLanYanElement(teamContext)
    priority = ["Pyro", "Hydro", "Electro", "Cryo"];
    counts = [ ...
        getFieldOrDefault(teamContext, 'PyroCount', 0), ...
        getFieldOrDefault(teamContext, 'HydroCount', 0), ...
        getFieldOrDefault(teamContext, 'ElectroCount', 0), ...
        getFieldOrDefault(teamContext, 'CryoCount', 0)];
    bestCount = 0;
    element = "";
    for i = 1:numel(priority)
        if counts(i) > bestCount
            bestCount = counts(i);
            element = priority(i);
        end
    end
end

function attackName = localResolveLanYanAbsorbAttack(element, useExtra)
    suffix = lower(char(string(element)));
    switch suffix
        case 'pyro'
            base = "ElementalArt_Bullet_Fire";
        case 'hydro'
            base = "ElementalArt_Bullet_Water";
        case 'electro'
            base = "ElementalArt_Bullet_Electric";
        case 'cryo'
            base = "ElementalArt_Bullet_Ice";
        otherwise
            base = "ElementalArt_Bullet_Wind";
    end
    if useExtra && base ~= "ElementalArt_Bullet_Wind"
        attackName = base + "_Extra";
    else
        attackName = base;
    end
end

function aura = localResolveLanYanAura(element, teamContext)
    switch lower(char(string(element)))
        case 'hydro'
            aura = "Pyro";
            if getFieldOrDefault(teamContext, 'PyroCount', 0) <= 0
                aura = "";
            end
        case 'pyro'
            if getFieldOrDefault(teamContext, 'HydroCount', 0) >= 1
                aura = "Hydro";
            elseif getFieldOrDefault(teamContext, 'CryoCount', 0) >= 1
                aura = "Cryo";
            else
                aura = "";
            end
        case 'cryo'
            if getFieldOrDefault(teamContext, 'PyroCount', 0) >= 1
                aura = "Pyro";
            else
                aura = "";
            end
        otherwise
            aura = "";
    end
end
