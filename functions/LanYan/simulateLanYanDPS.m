        ringTimeline(end + 1:ringCount) = 0.24; %#ok<AGROW>
    end

    allowAbsorbAmplify = any(strcmpi(absorbedElement, {'Hydro', 'Pyro', 'Cryo'}));
    allowAbsorbCatalyze = strcmpi(absorbedElement, 'Electro');
    allowAbsorbTransformative = any(strcmpi(absorbedElement, {'Hydro', 'Pyro', 'Cryo', 'Electro'}));

