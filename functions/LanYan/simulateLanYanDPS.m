    spec = struct( ...
        'Element', "Anemo", ...
        'ScalingMode', "ATK", ...
        'DefaultActionTime', 0.8, ...
        'DefaultRotation', {defaultRotation}, ...
        'ActionTimeMap', struct('N1', 0.34, 'N2', 0.38, 'N3', 0.40, 'N4', 0.48, ...
            'Charged', 0.72, 'EDash', 0.45, 'ERing', 0.85, 'EAbsorb', 0.01, ...
            'ERingExtra', 0.01, 'EAbsorbExtra', 0.01, 'Q', 1.00), ...
        'InitializeStateFn', @localInitializeLanYanState, ...
        'AfterActionFn', @localAfterLanYanAction, ...
        'AdvanceStateFn', @localAdvanceLanYanState, ...
        'Actions', actions);

    [totalDMG, dps, breakdown, rotationTime, audit] = simulateSimpleCharacterDPS( ...
        'LanYan', build, enemy, seqFile, talentLevel, constellation, teamContext, spec);
end

function state = localInitializeLanYanState(state, hookContext) %#ok<INUSD>
    state.TempEMBonus = 0;
    state.TempEMWindow = 0;
end

function [state, note] = localAfterLanYanAction(state, actionKey, actionSpec, actionDamage, reactionTags, note, hookContext) %#ok<INUSD>
    if actionKey == "Q" && getFieldOrDefault(hookContext, 'Constellation', 0) >= 4
        state.TempEMBonus = 60;
        state.TempEMWindow = 12.0;
        note = localAppendLanYanNote(note, "C4 EM");
    end
end

function state = localAdvanceLanYanState(state, actionTime, hookContext) %#ok<INUSD>
    if isfield(state, 'TempEMWindow') && state.TempEMWindow > 0
        state.TempEMWindow = max(0, state.TempEMWindow - actionTime);
        if state.TempEMWindow <= 1e-9
            state.TempEMBonus = 0;
        end
    end
end

function note = localAppendLanYanNote(baseNote, suffix)
    if strlength(string(baseNote)) == 0
        note = string(suffix);
    else
        note = string(baseNote) + ", " + string(suffix);
    end
end

function attackName = localResolveLanYanRingAttack(absorbedReady, element, useExtra)
    if absorbedReady
        attackName = localResolveLanYanAbsorbAttack(element, useExtra);
    else
        attackName = "ElementalArt_Bullet_Wind";
    end
end

function element = localResolveLanYanElement(teamContext)
    priority = ["Pyro", "Hydro", "Electro", "Cryo"];
    counts = [ ...
        getFieldOrDefault(teamContext, 'PyroCount', 0), ...
        getFieldOrDefault(teamContext, 'HydroCount', 0), ...
        getFieldOrDefault(teamContext, 'ElectroCount', 0), ...
        getFieldOrDefault(teamContext, 'CryoCount', 0)];
    bestCount = 0;
    element = "";
    for i = 1:numel(priority)
        if counts(i) > bestCount
            bestCount = counts(i);
            element = priority(i);
        end
    end
end

function attackName = localResolveLanYanAbsorbAttack(element, useExtra)
    suffix = lower(char(string(element)));
    switch suffix
        case 'pyro'
            base = "ElementalArt_Bullet_Fire";
        case 'hydro'
            base = "ElementalArt_Bullet_Water";
        case 'electro'
            base = "ElementalArt_Bullet_Electric";
        case 'cryo'
            base = "ElementalArt_Bullet_Ice";
        otherwise
            base = "ElementalArt_Bullet_Wind";
    end
    if useExtra && base ~= "ElementalArt_Bullet_Wind"
        attackName = base + "_Extra";
    else
        attackName = base;
    end
end

function aura = localResolveLanYanAura(element, teamContext)
    switch lower(char(string(element)))
        case 'hydro'
            aura = "Pyro";
            if getFieldOrDefault(teamContext, 'PyroCount', 0) <= 0
                aura = "";
            end
        case 'pyro'
            if getFieldOrDefault(teamContext, 'HydroCount', 0) >= 1
                aura = "Hydro";
            elseif getFieldOrDefault(teamContext, 'CryoCount', 0) >= 1
                aura = "Cryo";
            else
                aura = "";
            end
        case 'cryo'
            if getFieldOrDefault(teamContext, 'PyroCount', 0) >= 1
                aura = "Pyro";
            else
                aura = "";
            end
        otherwise
            aura = "";
    end
end
