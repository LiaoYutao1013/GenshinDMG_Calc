        'TalentGroup', "Normal", ...
        'Param', "x2HitDMG", ...
        'DamageField', "NormalDMGBonus", ...
        'ActionElement', "Anemo", ...
        'BaseMultiplier', 0.50, ...
        'HitCount', 2, ...
        'HitTimeline', [0.00, 0.08], ...
        'ApplyGauge', 1.0, ...
        'ICDGroup', "LanYan_Normal", ...
        'ICDRule', "Independent", ...
        'AllowTransformative', 1, ...
        'ReactionElement', "Anemo", ...
        'ReactionBaseDamage', 723.0, ...
