function rotation = localBuildDefaultRotation(stellarConductReady, constellation)
    if stellarConductReady
        if constellation >= 2
            n3Stellar = 'N3StellarC2';
            n5Stellar = 'N5StellarC2';
            n5StellarBuffed = 'N5StellarBuffedC2';
            lusterStellar = 'LusterStellarBuffedC2';
        else
            n3Stellar = 'N3Stellar';
            n5Stellar = 'N5Stellar';
            n5StellarBuffed = 'N5StellarBuffed';
            lusterStellar = 'LusterStellarBuffed';
        end
        if constellation >= 1
            lusterMain = 'LusterBuffed';
        else
            lusterMain = 'Luster';
        end

        rotation = {'E', 'N1', 'N2', 'N3', n3Stellar, 'N4', 'N5'};
        if constellation >= 6
            rotation{end + 1} = 'N5Icicle';
        end
        rotation = [rotation, {n5Stellar, lusterMain}];
        if constellation >= 6
            rotation{end + 1} = 'LusterIcicle';
        end
        rotation = [rotation, {lusterStellar, 'N1', 'N2', 'N3', n3Stellar, 'N4', 'N5'}];
        if constellation >= 6
            rotation{end + 1} = 'N5Icicle';
        end
        rotation = [rotation, {n5StellarBuffed, lusterMain}];
        if constellation >= 6
            rotation{end + 1} = 'LusterIcicle';
        end
        rotation = [rotation, {lusterStellar, 'Q', 'Blade'}];
        return;
    end

    if constellation >= 2
        secondCycleNormals = {'N1C2', 'N2C2', 'N3C2', 'N4C2', 'N5C2'};
        rebukeAction = 'RebukeC2';
    else
        secondCycleNormals = {'N1', 'N2', 'N3', 'N4', 'N5'};
        rebukeAction = 'Rebuke';
    end

    rotation = {'E', 'N1', 'N2', 'N3', 'N4', 'N5', rebukeAction};
    if constellation >= 6
        rotation{end + 1} = 'C6Icicle';
    end
    rotation = [rotation, secondCycleNormals, {rebukeAction}];
    if constellation >= 6
        rotation{end + 1} = 'C6Icicle';
    end
    rotation = [rotation, {'Q', 'Blade'}];
end

function timeMap = localBuildActionTimeMap(constellation, stellarConductReady)
    timeMap = struct();
    timeMap.E = 0.60;
    timeMap.N1 = 0.35;
    timeMap.N2 = 0.35;
    timeMap.N3 = 0.40;
    timeMap.N4 = 0.45;
    timeMap.N5 = 0.55;
    timeMap.Rebuke = 0.80;
    timeMap.RebukeC2 = 0.80;
    timeMap.Luster = 0.80;
    timeMap.LusterBuffed = 0.80;
    timeMap.Q = 1.10;
    timeMap.Blade = 0.35;
    timeMap.C6Icicle = 0.01;
    timeMap.N5Icicle = 0.01;
    timeMap.LusterIcicle = 0.01;

    timeMap.N1C2 = 0.35;
    timeMap.N2C2 = 0.35;
    timeMap.N3C2 = 0.40;
    timeMap.N4C2 = 0.45;
    timeMap.N5C2 = 0.55;

    timeMap.N3Stellar = 0.01;
    timeMap.N5Stellar = 0.01;
    timeMap.N5StellarBuffed = 0.01;
    timeMap.LusterStellar = 0.01;
    timeMap.LusterStellarBuffed = 0.01;

    if constellation >= 2 && stellarConductReady
        timeMap.N3StellarC2 = 0.01;
        timeMap.N5StellarC2 = 0.01;
        timeMap.N5StellarBuffedC2 = 0.01;
        timeMap.LusterStellarC2 = 0.01;
        timeMap.LusterStellarBuffedC2 = 0.01;
    end
end
