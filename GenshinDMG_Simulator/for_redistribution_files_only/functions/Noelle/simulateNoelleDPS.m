        'ApplyGauge', 0.0, ...
        'CanApplyAura', false, ...
        'ICDGroup', "Noelle_Normal", ...
        'ICDRule', "Standard (3h/2.5s)", ...
        'StrikeType', "Blunt", ...
        'CanShatter', true, ...
        'Note', string(note));
end

