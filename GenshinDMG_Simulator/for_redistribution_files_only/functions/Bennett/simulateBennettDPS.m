        'Element', "Pyro", ...
        'ScalingMode', "ATK", ...
        'DefaultActionTime', 0.60, ...
        'DefaultRotation', {{'Q', 'E', 'N1', 'N2', 'E'}}, ...
        'ActionTimeMap', struct( ...
            'E', 0.44, ...
            'E1A', 0.30, ...
            'E1B', 0.36, ...
            'E2A', 0.34, ...
            'E2B', 0.34, ...
            'EExplode', 0.24, ...
            'Q', 0.98, ...
            'N1', 0.34, ...
            'N2', 0.40), ...
        'Actions', actions);

    [totalDMG, dps, breakdown, rotationTime, audit] = simulateSimpleCharacterDPS( ...
        'Bennett', build, enemy, seqFile, talentLevel, constellation, teamContext, spec);
