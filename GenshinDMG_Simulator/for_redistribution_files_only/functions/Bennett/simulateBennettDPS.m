function [totalDMG, dps, breakdown, rotationTime, audit] = simulateBennettDPS(build, enemy, seqFile, talentLevel, constellation, teamContext)
    % Bennett simulator with tap / charge skill branches, burst cast, and
    % C6 Pyro-infused normals for carry-field testing.
    if nargin < 3 || isempty(seqFile)
        seqFile = fullfile(fileparts(mfilename('fullpath')), '..', '..', 'data', 'Bennett', 'rotation_Bennett.txt');
    end
    if nargin < 4 || isempty(talentLevel)
        talentLevel = 10;
    end
    if nargin < 5 || isempty(constellation)
        constellation = 0;
    end
    if nargin < 6 || isempty(teamContext)
        teamContext = buildTeamContext({struct('Name', 'Bennett', 'Constellation', constellation, 'Build', build)}, 20, struct());
    end

    infusedElement = "Physical";
    if constellation >= 6
        infusedElement = "Pyro";
    end

    actions = struct();
    actions.E = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "PressDMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Pyro", ...
        'BaseMultiplier', 1.00, ...
        'AllowAmplify', 1, ...
        'PreferredAmplifyAura', "Hydro", ...
        'ApplyGauge', 2.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ElementalArt_Strike01_01", ...
        'LunarisDamageParam', "Strike_01", ...
        'Note', "Passion Overload tap");
    actions.E1A = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "ChargeLevel1DMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Pyro", ...
        'BaseMultiplier', 1.00, ...
        'AllowAmplify', 1, ...
        'PreferredAmplifyAura', "Hydro", ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ElementalArt_Strike02_01", ...
        'LunarisDamageParam', "Strike_02_01", ...
        'Note', "Passion Overload charge 1 hit 1");
    actions.E1B = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "ChargeLevel1DMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Pyro", ...
        'MVOverride', 1.0, ...
        'AllowAmplify', 1, ...
        'PreferredAmplifyAura', "Hydro", ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ElementalArt_Strike02_02", ...
        'LunarisDamageParam', "Strike_02_02", ...
        'Note', "Passion Overload charge 1 hit 2");
    actions.E2A = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "ChargeLevel2DMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Pyro", ...
        'BaseMultiplier', 1.00, ...
        'AllowAmplify', 1, ...
        'PreferredAmplifyAura', "Hydro", ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ElementalArt_Strike03_01", ...
        'LunarisDamageParam', "Strike_03_01", ...
        'Note', "Passion Overload charge 2 hit 1");
    actions.E2B = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "ChargeLevel2DMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Pyro", ...
        'MVOverride', 1.0, ...
        'AllowAmplify', 1, ...
        'PreferredAmplifyAura', "Hydro", ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ElementalArt_Strike03_02", ...
        'LunarisDamageParam', "Strike_03_02", ...
        'Note', "Passion Overload charge 2 hit 2");
    actions.EExplode = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "ExplosionDMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Pyro", ...
        'BaseMultiplier', 1.00, ...
        'AllowAmplify', 1, ...
        'PreferredAmplifyAura', "Hydro", ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ElementalArt_Explode", ...
        'LunarisDamageParam', "Strike_03_03", ...
        'Note', "Passion Overload explosion");
    actions.Q = struct( ...
        'TalentGroup', "Burst", ...
        'Param', "SkillDMG", ...
        'DamageField', "BurstDMGBonus", ...
        'ActionElement', "Pyro", ...
        'BaseMultiplier', 1.00, ...
        'AllowAmplify', 1, ...
        'PreferredAmplifyAura', "Hydro", ...
        'PostSetBurstActiveTime', 12.0, ...
        'ApplyGauge', 2.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', "ElementalBurst_Strike", ...
        'LunarisDamageParam', "Burst_DMG", ...
        'Note', "Fantastic Voyage cast");
    actions.N1 = struct( ...
        'TalentGroup', "Normal", ...
        'Param', "x1HitDMG", ...
        'DamageField', "NormalDMGBonus", ...
        'ActionElement', infusedElement, ...
        'BaseMultiplier', 1.00, ...
        'BurstWindowDamageBonus', 0.15 * double(constellation >= 6), ...
        'AllowAmplify', double(strcmpi(char(infusedElement), 'Pyro')), ...
