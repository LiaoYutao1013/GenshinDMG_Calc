        'DamageField', "NormalDMGBonus", ...
        'ActionElement', "Physical", ...
        'BaseMultiplier', 1.00, ...
        'FlatDirectHPWeight', 0.0139, ...
        'SkillWindowExtraResShred', 0.20, ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'LunarisAttackName', string(attackName), ...
        'LunarisDamageParam', string(damageParam), ...
        'Note', string(note));
end
