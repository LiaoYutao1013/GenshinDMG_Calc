function [totalDMG, dps, breakdown, rotationTime, audit] = simulateRaidenShogunDPS(build, enemy, seqFile, talentLevel, constellation, teamContext)
    % Raiden Shogun 高精度反应元数据模拟。
    % 这里先聚焦统一反应引擎最敏感的部分：
    % 1. E 起手命中与协同雷击拆分，并给出真实 Gauge / ICD；
    % 2. Q 梦想一刀与梦想一心期间的普攻 / 重击 / 下落拆分；
    % 3. Burst 期普攻按 Burst 伤害窗结算，并显式写入 Lunaris 攻击名。
    if nargin < 3 || isempty(seqFile)
        seqFile = fullfile(fileparts(mfilename('fullpath')), '..', '..', 'data', 'RaidenShogun', 'rotation_RaidenShogun.txt');
    end
    if nargin < 4 || isempty(talentLevel)
        talentLevel = 10;
    end
    if nargin < 5 || isempty(constellation)
        constellation = 0;
    end
    if nargin < 6 || isempty(teamContext)
        teamContext = buildTeamContext({struct('Name', 'RaidenShogun', 'Constellation', constellation, 'Build', build)}, 20, struct());
    end

    aggravateReady = getFieldOrDefault(teamContext, 'DendroCount', 0) >= 1;
    burstResolveStacks = localResolveDefaultResolveStacks(teamContext, constellation);
    burstTalentLevel = talentLevel + 3 * double(constellation >= 5);
    resolveBonusMV = getTalentValue(localReadTalentTable(), 'Burst', 'ResolveBonus', burstTalentLevel) * burstResolveStacks;

    actions = struct();
