    if constellation >= 2
        build = applyStructOverrides(build, struct('EnemyDefReduct', ...
            getFieldOrDefault(build, 'EnemyDefReduct', 0) + 0.60));
    end

    [totalDMG, dps, breakdown, rotationTime, audit] = simulateSimpleCharacterDPS( ...
        'RaidenShogun', build, enemy, seqFile, talentLevel, constellation, teamContext, spec);
end

function action = localBurstNormalAction(paramName, attackName, damageParam, gauge, note, aggravateReady)
    action = struct( ...
        'TalentGroup', "Burst", ...
        'Param', string(paramName), ...
        'DamageField', "BurstDMGBonus", ...
        'ActionElement', "Electro", ...
        'BaseMultiplier', 1.00, ...
        'AllowCatalyze', double(aggravateReady), ...
        'LunarisAttackName', string(attackName), ...
        'LunarisDamageParam', string(damageParam), ...
        'ApplyGauge', double(gauge), ...
        'ICDRule', "Independent", ...
        'Note', string(note));
end

function resolveStacks = localResolveDefaultResolveStacks(teamContext, constellation)
    memberCount = getFieldOrDefault(teamContext, 'MemberCount', 1);
    memberConstellations = getFieldOrDefault(teamContext, 'MemberConstellations', 0);
    memberNames = string(getFieldOrDefault(teamContext, 'MemberNames', "RaidenShogun"));
    energyTemplate = [60 70 80 80];
    resolvePerEnergy = 0.19;
    if constellation >= 1
        resolvePerEnergy = resolvePerEnergy * 1.20;
    end

    resolveStacks = 0;
    for i = 1:min(memberCount, numel(energyTemplate))
        if memberNames(i) == "RaidenShogun"
            continue;
        end
        gainMultiplier = 1.0;
        if getCharacterElement(memberNames(i)) == "Electro"
            gainMultiplier = 1.8;
        end
        resolveStacks = resolveStacks + energyTemplate(i) * resolvePerEnergy * gainMultiplier;
    end
    resolveStacks = min(60, max(36, resolveStacks + 6 * double(any(memberConstellations >= 1))));
end

function talent = localReadTalentTable()
    persistent talentTable
    if isempty(talentTable)
        talentPath = fullfile(fileparts(mfilename('fullpath')), '..', '..', 'data', 'RaidenShogun', 'talents_RaidenShogun.csv');
        talentTable = readtable(talentPath);
    end
    talent = talentTable;
end
