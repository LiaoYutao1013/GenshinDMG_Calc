        'TalentGroup', "Skill", ...
        'Param', "SkillDMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Electro", ...
        'BaseMultiplier', 1.00, ...
        'AllowCatalyze', double(aggravateReady), ...
        'LunarisAttackName', "SkillObj_ElementalArt_EyeBoom", ...
        'LunarisDamageParam', "ElementalArt_Attack", ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'Note', "Transcendence: Baleful Omen cast");
    actions.Eye = struct( ...
        'TalentGroup', "Skill", ...
        'Param', "CoordinatedATKDMG", ...
        'DamageField', "SkillDMGBonus", ...
        'ActionElement', "Electro", ...
        'BaseMultiplier', 1.00, ...
        'HitCount', 12, ...
        'HitTimeline', [0.9, 0.9 * ones(1, 11)], ...
        'AllowCatalyze', double(aggravateReady), ...
        'LunarisAttackName', "Elf", ...
        'LunarisDamageParam', "Elf_Attack|Elf_RemoteAttackRatio|MUL", ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'Note', "Eye of Stormy Judgment coordinated attacks");
    actions.Q = struct( ...
        'TalentGroup', "Burst", ...
        'Param', "MusouNoHitotachiBaseDMG", ...
        'DamageField', "BurstDMGBonus", ...
        'ActionElement', "Electro", ...
        'FlatMVBonus', resolveBonusMV, ...
        'BaseMultiplier', 1.00, ...
        'AllowCatalyze', double(aggravateReady), ...
        'PostSetBurstActiveTime', getTalentValue(localReadTalentTable(), 'Burst', 'MusouIsshinDuration', burstTalentLevel), ...
        'LunarisAttackName', "ElementalBurst", ...
        'LunarisDamageParam', "ElementalBurst_BaseDamage|BurstDamageDelta|ADD", ...
        'ApplyGauge', 2.0, ...
        'ICDRule', "Independent", ...
        'Note', "Secret Art: Musou Shinsetsu");
    actions.B1 = localBurstNormalAction("x1HitDMG", "FallingAnthem", "FallingAnthem_Normal_Rank_1_Katana_Damage|KatanaDamageDelta|ADD", 1.0, "Burst normal 1", aggravateReady);
    actions.B2 = localBurstNormalAction("x2HitDMG", "FallingAnthem", "FallingAnthem_Normal_Rank_2_Katana_Damage|KatanaDamageDelta|ADD", 1.0, "Burst normal 2", aggravateReady);
    actions.B3 = localBurstNormalAction("x3HitDMG", "FallingAnthem", "FallingAnthem_Normal_Loop_Katana_Damage|KatanaDamageDelta|ADD", 0.0, "Burst normal 3", aggravateReady);
    actions.B4 = localBurstNormalAction("x4HitDMG", "FallingAnthem", "FallingAnthem_Normal_Loop_Katana_Damage|KatanaDamageDelta|ADD", 0.0, "Burst normal 4", aggravateReady);
    actions.B5 = localBurstNormalAction("x5HitDMG", "FallingAnthem", "FallingAnthem_Normal_Loop_Katana_Damage|KatanaDamageDelta|ADD", 0.0, "Burst normal 5", aggravateReady);
    actions.BCA = struct( ...
        'TalentGroup', "Burst", ...
        'Param', "ChargedAttackDMG", ...
        'DamageField', "BurstDMGBonus", ...
        'ActionElement', "Electro", ...
        'BaseMultiplier', 1.00, ...
        'AllowCatalyze', double(aggravateReady), ...
        'LunarisAttackName', "FallingAnthem", ...
        'LunarisDamageParam', "FallingAnthem_Normal_Loop_Katana_Damage|KatanaDamageDelta|ADD", ...
        'ApplyGauge', 0.0, ...
        'ICDRule', "Independent", ...
        'Note', "Burst charged attack");
    actions.BPlunge = struct( ...
        'TalentGroup', "Burst", ...
        'Param', "LowHighPlungeDMG", ...
        'DamageField', "BurstDMGBonus", ...
        'ActionElement', "Electro", ...
        'BaseMultiplier', 1.00, ...
        'ActionScalingMode', "ATK", ...
        'AllowCatalyze', 0, ...
        'LunarisAttackName', "FallingAnthem", ...
        'LunarisDamageParam', "FallingAnthem_Normal_Rank_2_Katana_Damage|KatanaDamageDelta|ADD", ...
        'ApplyGauge', 1.0, ...
        'ICDRule', "Independent", ...
        'Note', "Burst high plunge");

    spec = struct( ...
        'Element', "Electro", ...
        'ScalingMode', "ATK", ...
        'DefaultActionTime', 0.55, ...
        'DefaultRotation', {{'E', 'Q', 'B1', 'B2', 'B3', 'B4', 'B5', 'BCA', 'B1', 'B2', 'B3', 'B4', 'B5', 'Eye'}}, ...
        'ActionTimeMap', struct( ...
